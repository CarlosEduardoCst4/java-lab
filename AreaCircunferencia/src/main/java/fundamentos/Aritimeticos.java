package fundamentos;

public class Aritimeticos {
    static void main(String[] args) {
        System.out.println(2+3);

        var a = 23.456;
        double b = 32.45;

        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);

        int x = 5;
        int y = 8;

        System.out.println(x+y);
        System.out.println(x-y);
        System.out.println(x*y);
        System.out.println(x/y);
        System.out.println(x/(double)y);
        System.out.println(x/(float)y);
        System.out.println(x%y);
        System.out.println(a%b);
    }
}
